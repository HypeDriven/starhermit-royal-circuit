// Writes the native play scripts (tests/native/*.play) that tests/native.mjs
// runs with `starhermit . --render-check --script`:
//   journey-keys.play   Journey stages 1 and 2 on a desktop by keys (Enter rolls, moves the
//                       picked float, passes), each to its results, "Next: Stage 2" between;
//   learn-phone.play    the six lessons on a DPR-3 phone by finger: the Turn drawer opened,
//                       Roll, the float picker's buttons and Pass touched, each lesson to
//                       "Lesson Complete!" and on to the next;
//   menus.play          the menus on a desktop: How to Play, Settings (palette, theme, camera,
//                       captions), Achievements, Leaderboards, Profile, the Learn and Challenge
//                       lists, a 3-player Practice paused, its settings and rules opened, undo
//                       and the hint used, then left;
//   daily-land.play     today's Daily Circuit (any day: a key loop) in short landscape to its
//                       results.
// The lesson script follows the rules: each human decision is simulated with
// the shipped session (forced lesson dice, the AI's seeded choices) and the
// lesson's steps advance as native/main.ts advances them.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Session } from '../src/session.js';
import { LESSONS } from '../src/content.js';
import { circuitCell, isSafeCell } from '../src/rules.js';
import { aiName } from '../src/ai.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = (name, lines) => writeFileSync(join(root, 'tests', 'native', name), lines.join('\n') + '\n');

/** main.ts describeMove in English. */
function describeMove(state, m) {
  const n = m.floatId + 1;
  if (m.deploys) return `Float ${n}: kindle!`;
  if (m.crowns) return `Float ${n}: CROWN 👑`;
  if (m.captures.length) return `Float ${n}: capture!`;
  const cell = circuitCell(state.ruleset, state.turnIndex, m.to);
  if (cell !== null && isSafeCell(state.ruleset, cell)) return `Float ${n}: to lantern tile`;
  return `Float ${n}: move ${state.die}`;
}

/** The human's decisions through a lesson until its last step ("complete") is reached. */
export function lessonDecisions(lesson) {
  const s = new Session({
    mode: 'learn', lesson, seed: lesson.ruleset.seed, ruleset: lesson.ruleset,
    players: [{ name: 'Guest Envoy', kind: 'human' }, { kind: 'ai', level: 1, name: aiName(1, 0) }],
    ranked: false, undoAllowed: true, now: () => 0,
  });
  const batches = [];
  s.onEvent = (events) => batches.push(events);
  let step = 0;
  const advance = () => {
    for (const evs of batches.splice(0)) {
      const st = lesson.steps[step];
      if (!st || st.action === 'complete') continue;
      const ok = {
        roll: () => evs.some((e) => e.t === 'roll' && e.seat === 0),
        deploy: () => evs.some((e) => e.t === 'deploy' && e.seat === 0),
        move: () => evs.some((e) => e.t === 'move' && e.seat === 0),
        capture: () => evs.some((e) => e.t === 'capture' && e.bySeat === 0),
        crown: () => evs.some((e) => e.t === 'crown' && e.seat === 0),
      }[st.action]?.();
      if (ok) step++;
    }
  };
  const out = [];
  for (let guard = 0; guard < 200 && lesson.steps[step]?.action !== 'complete' && !s.isOver; guard++) {
    if (s.currentPlayer.kind === 'ai') { s.aiStep(); advance(); continue; }
    const acts = s.actions;
    if (acts.type === 'roll') { out.push({ wait: 'Your turn — roll!', touch: 'Roll the festival die' }); s.command('roll'); }
    else if (acts.type === 'pass') { out.push({ wait: 'No moves — you must pass.', touch: '=Pass' }); s.command('pass'); }
    else {
      const m = s.hint() || acts.moves[0];
      const label = describeMove(s.state, m);
      out.push({ wait: label, touch: `=${label}` });
      s.command('move', { floatId: m.floatId });
    }
    advance();
  }
  if (lesson.steps[step]?.action !== 'complete') throw new Error(`${lesson.id}: the lesson did not complete`);
  return out;
}

// ------------------------------------------------------------------ learn-phone.play
{
  const L = [
    '# Generated by tools/gen-plays.mjs: the six lessons on a DPR-3 phone by finger (the Turn drawer, Roll, the float picker, Pass).',
    '# viewport 390x844@3',
    'until 600 Daily Circuit',
    'frames 30',
    'touch =Learn',
    'until 300 Learn the Circuit',
    'frames 10',
    'touch Kindling a Float.',
  ];
  LESSONS.forEach((lesson, i) => {
    L.push(`# ${lesson.id}`, 'until 300 Expected duration', 'frames 10');
    if (i === 0) L.push('save setup');
    L.push('touch =Start', 'until 600 Hint', 'frames 60', 'touch =Turn', 'frames 10');
    if (i === 0) L.push('save lesson-1');
    for (const d of lessonDecisions(lesson)) {
      L.push(`until 1500 ${d.wait}`, 'frames 5', `touch ${d.touch}`, 'frames 10');
    }
    L.push('until 1200 Lesson Complete!', 'frames 20');
    if (i === 0) L.push('save lesson-done');
    if (i + 1 < LESSONS.length) L.push(`touch =Next: ${LESSONS[i + 1].title}`, 'frames 10');
  });
  L.push('expect Back to title', 'touch =Back to title', 'until 300 Daily Circuit', 'frames 10', 'touch =Learn', 'until 300 Learn the Circuit', 'frames 20', 'save learn-done');
  out('learn-phone.play', L);
}

